-- TIKETIIN DATABASE
-- Tahap 08: Notification

begin;

-- 1. Tabel notifications
create table public.notifications (
    id integer generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id) on delete cascade,

    title text not null,

    message text not null,

    type text not null default 'GENERAL'
        check (type in (
            'GENERAL',
            'ORDER',
            'PAYMENT',
            'ESCROW',
            'KYC',
            'PRICE_ALERT',
            'HOT_OPPORTUNITY',
            'RECOMMENDATION',
            'EVENT_REMINDER'
        )),

    event_id integer
        references public.events(id) on delete set null,

    order_id integer
        references public.orders(id) on delete set null,

    is_read boolean not null default false,

    created_at timestamptz not null default now()
);

-- 2. Mengaktifkan RLS
alter table public.notifications
enable row level security;

-- 3. Mengatur hak akses
revoke all on public.notifications
from anon, authenticated;

grant select, delete
on public.notifications to authenticated;

grant update (is_read)
on public.notifications to authenticated;

-- 4. Pengguna hanya dapat melihat notifikasi sendiri
create policy "Read own notifications"
on public.notifications
for select
to authenticated
using (auth.uid() = user_id);

-- 5. Pengguna dapat menandai notifikasi sudah dibaca
create policy "Update own notifications"
on public.notifications
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- 6. Pengguna dapat menghapus notifikasi sendiri
create policy "Delete own notifications"
on public.notifications
for delete
to authenticated
using (auth.uid() = user_id);

-- 7. Index database
create index idx_notifications_user
on public.notifications(user_id);

create index idx_notifications_read
on public.notifications(user_id, is_read);

create index idx_notifications_created
on public.notifications(created_at desc);

commit;
