-- TIKETIIN DATABASE
-- Tahap 04: Ticket Management

begin;

-- 1. Tabel ticket_listings
create table public.ticket_listings (
    id integer generated by default as identity primary key,

    event_id integer not null
        references public.events(id),

    seller_id uuid not null
        references public.profiles(id),

    seat_category text not null,
    seat_row text not null default '',

    face_value bigint not null
        check (face_value > 0),

    price bigint not null
        check (price > 0),

    quantity integer not null
        check (quantity >= 0),

    status text not null default 'AKTIF'
        check (status in (
            'AKTIF',
            'TERJUAL',
            'NONAKTIF'
        )),

    views integer not null default 0
        check (views >= 0),

    saves integer not null default 0
        check (saves >= 0),

    offers integer not null default 0
        check (offers >= 0),

    created_at timestamptz not null default now(),

    constraint fair_price_limit
        check (price <= face_value::numeric * 1.5),

    constraint active_stock_check
        check (status <> 'AKTIF' or quantity > 0)
);

-- 2. Tabel verifications
create table public.verifications (
    id integer generated by default as identity primary key,

    user_id uuid not null unique
        references public.profiles(id) on delete cascade,

    status text not null default 'PENDING'
        check (status in (
            'PENDING',
            'VERIFIED',
            'REJECTED'
        )),

    rejection_reason text,
    submitted_at timestamptz not null default now(),
    verified_at timestamptz
);

-- 3. Mengaktifkan RLS
alter table public.ticket_listings
enable row level security;

alter table public.verifications
enable row level security;

-- 4. Mengatur hak akses
revoke all on public.ticket_listings,
public.verifications
from anon, authenticated;

grant select on public.ticket_listings
to anon, authenticated;

grant insert (
    event_id, seller_id, seat_category,
    seat_row, face_value, price, quantity
)
on public.ticket_listings to authenticated;

grant update (
    seat_category, seat_row, price, status
)
on public.ticket_listings to authenticated;

grant select on public.verifications
to authenticated;

grant insert (user_id)
on public.verifications to authenticated;

-- 5. Buyer dapat melihat tiket aktif
create policy "Read active listings"
on public.ticket_listings
for select
to anon, authenticated
using (
    status = 'AKTIF'
    and quantity > 0
    and exists (
        select 1 from public.events
        where id = event_id
        and date >= current_date
    )
);

-- 6. Seller dapat melihat listing sendiri
create policy "Read own listings"
on public.ticket_listings
for select
to authenticated
using (auth.uid() = seller_id);

-- 7. Seller terverifikasi dapat menjual tiket
create policy "Insert verified seller listings"
on public.ticket_listings
for insert
to authenticated
with check (
    auth.uid() = seller_id
    and exists (
        select 1 from public.profiles
        where id = auth.uid()
        and is_kyc_verified = true
    )
    and exists (
        select 1 from public.events
        where id = event_id
        and date >= current_date
    )
);

-- 8. Seller dapat mengubah listing sendiri
create policy "Update own listings"
on public.ticket_listings
for update
to authenticated
using (
    auth.uid() = seller_id
    and status <> 'TERJUAL'
)
with check (
    auth.uid() = seller_id
    and status in ('AKTIF', 'NONAKTIF')
    and exists (
        select 1 from public.profiles
        where id = auth.uid()
        and is_kyc_verified = true
    )
    and (
        status = 'NONAKTIF'
        or exists (
            select 1 from public.events
            where id = event_id
            and date >= current_date
        )
    )
);

-- 9. Pengguna dapat melihat status verifikasi sendiri
create policy "Read own verification"
on public.verifications
for select
to authenticated
using (auth.uid() = user_id);

-- 10. Pengguna dapat mengajukan verifikasi
create policy "Submit own verification"
on public.verifications
for insert
to authenticated
with check (
    auth.uid() = user_id
    and status = 'PENDING'
);

-- 11. Index database
create index idx_listings_event
on public.ticket_listings(event_id);

create index idx_listings_seller
on public.ticket_listings(seller_id);

create index idx_listings_status
on public.ticket_listings(status);

commit;
