-- TIKETIIN DATABASE
-- Tahap 07: Hotel Management

begin;

-- 1. Tabel hotels
create table public.hotels (
    id integer generated by default as identity primary key,

    name text not null,
    address text not null default '',
    city text not null,

    latitude double precision not null
        check (latitude between -90 and 90),

    longitude double precision not null
        check (longitude between -180 and 180),

    price_per_night bigint not null
        check (price_per_night > 0),

    rating numeric(2,1) not null default 0
        check (rating between 0 and 5),

    description text not null default '',

    image_url text,
    booking_url text,

    is_active boolean not null default true,

    created_at timestamptz not null default now(),

    unique (name, address, city)
);

-- 2. Tabel hotel_availability
create table public.hotel_availability (
    id integer generated by default as identity primary key,

    hotel_id integer not null
        references public.hotels(id) on delete cascade,

    date date not null,

    available_rooms integer not null default 0
        check (available_rooms >= 0),

    price_per_night bigint
        check (price_per_night > 0),

    updated_at timestamptz not null default now(),

    unique (hotel_id, date)
);

-- 3. Mengaktifkan RLS
alter table public.hotels
enable row level security;

alter table public.hotel_availability
enable row level security;

-- 4. Mengatur hak akses
revoke all on public.hotels,
public.hotel_availability
from anon, authenticated;

grant select on public.hotels,
public.hotel_availability
to authenticated;

-- 5. Pengguna dapat melihat hotel aktif
create policy "Read active hotels"
on public.hotels
for select
to authenticated
using (is_active = true);

-- 6. Pengguna dapat melihat ketersediaan kamar
create policy "Read hotel availability"
on public.hotel_availability
for select
to authenticated
using (
    date >= current_date
    and exists (
        select 1
        from public.hotels
        where hotels.id = hotel_availability.hotel_id
        and hotels.is_active = true
    )
);

-- 7. Index database
create index idx_hotels_city
on public.hotels(city);

create index idx_hotels_location
on public.hotels(latitude, longitude);

create index idx_hotel_availability_date
on public.hotel_availability(date);

commit;
