-- TIKETIIN DATABASE
-- Tahap 05: User Interactions

begin;

-- 1. Tabel wishlists
create table public.wishlists (
    id integer generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id) on delete cascade,

    event_id integer not null
        references public.events(id) on delete cascade,

    created_at timestamptz not null default now(),

    unique (user_id, event_id)
);

-- 2. Tabel event_views
create table public.event_views (
    id bigint generated always as identity primary key,

    user_id uuid not null
        references public.profiles(id) on delete cascade,

    event_id integer not null
        references public.events(id) on delete cascade,

    viewed_at timestamptz not null default now(),

    viewed_on date not null default current_date,

    unique (user_id, event_id, viewed_on)
);

-- 3. Mengaktifkan RLS
alter table public.wishlists
enable row level security;

alter table public.event_views
enable row level security;

-- 4. Mengatur hak akses
revoke all on public.wishlists,
public.event_views
from anon, authenticated;

grant select, delete on public.wishlists
to authenticated;

grant insert (user_id, event_id)
on public.wishlists to authenticated;

grant select on public.event_views
to authenticated;

grant insert (user_id, event_id)
on public.event_views to authenticated;

-- 5. Pengguna dapat melihat wishlist sendiri
create policy "Read own wishlist"
on public.wishlists
for select
to authenticated
using (auth.uid() = user_id);

-- 6. Pengguna dapat menambahkan wishlist
create policy "Insert own wishlist"
on public.wishlists
for insert
to authenticated
with check (auth.uid() = user_id);

-- 7. Pengguna dapat menghapus wishlist sendiri
create policy "Delete own wishlist"
on public.wishlists
for delete
to authenticated
using (auth.uid() = user_id);

-- 8. Pengguna dapat melihat riwayat view sendiri
create policy "Read own event views"
on public.event_views
for select
to authenticated
using (auth.uid() = user_id);

-- 9. Pengguna dapat mencatat aktivitas view
create policy "Insert own event views"
on public.event_views
for insert
to authenticated
with check (auth.uid() = user_id);

-- 10. Index database
create index idx_wishlists_event
on public.wishlists(event_id);

create index idx_event_views_event
on public.event_views(event_id);

create index idx_event_views_date
on public.event_views(viewed_at);

commit;
