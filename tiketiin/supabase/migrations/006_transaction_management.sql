-- TIKETIIN DATABASE
-- Tahap 06: Transaction Management

begin;

-- 1. Tabel orders
create table public.orders (
    id integer generated by default as identity primary key,

    order_code text not null unique,

    buyer_id uuid not null
        references public.profiles(id),

    seller_id uuid not null
        references public.profiles(id),

    event_id integer not null
        references public.events(id),

    listing_id integer not null
        references public.ticket_listings(id),

    quantity integer not null
        check (quantity > 0),

    unit_price bigint not null
        check (unit_price > 0),

    service_fee bigint not null default 0
        check (service_fee >= 0),

    total_price bigint generated always as (
        quantity * unit_price + service_fee
    ) stored,

    buyer_name text not null,
    buyer_email text not null,
    buyer_phone text not null default '',

    status text not null default 'PENDING'
        check (status in (
            'PENDING',
            'PAID',
            'COMPLETED',
            'CANCELLED',
            'EXPIRED',
            'REFUNDED'
        )),

    qr_code text unique,

    expires_at timestamptz not null
        default (now() + interval '10 minutes'),

    paid_at timestamptz,
    completed_at timestamptz,

    created_at timestamptz not null default now(),

    constraint different_buyer_seller
        check (buyer_id <> seller_id)
);

-- 2. Tabel payments
create table public.payments (
    id integer generated by default as identity primary key,

    order_id integer not null unique
        references public.orders(id),

    payment_method text not null,

    amount bigint not null
        check (amount > 0),

    payment_reference text unique,

    status text not null default 'PENDING'
        check (status in (
            'PENDING',
            'SUCCESS',
            'FAILED',
            'EXPIRED',
            'REFUNDED'
        )),

    escrow_status text not null default 'PENDING'
        check (escrow_status in (
            'PENDING',
            'HELD',
            'RELEASED',
            'REFUNDED'
        )),

    paid_at timestamptz,
    released_at timestamptz,
    refunded_at timestamptz,

    created_at timestamptz not null default now()
);

-- 3. Mengaktifkan RLS
alter table public.orders
enable row level security;

alter table public.payments
enable row level security;

-- 4. Mengatur hak akses
revoke all on public.orders, public.payments
from anon, authenticated;

grant select on public.orders
to authenticated;

grant select on public.payments
to authenticated;

-- 5. Buyer dapat melihat pesanan sendiri
create policy "Read own buyer orders"
on public.orders
for select
to authenticated
using (auth.uid() = buyer_id);

-- 6. Seller dapat melihat pesanan tiketnya
create policy "Read own seller orders"
on public.orders
for select
to authenticated
using (auth.uid() = seller_id);

-- 7. Buyer dan seller dapat melihat pembayaran
-- yang berkaitan dengan transaksi mereka
create policy "Read own transaction payments"
on public.payments
for select
to authenticated
using (
    exists (
        select 1
        from public.orders
        where orders.id = payments.order_id
        and (
            orders.buyer_id = auth.uid()
            or orders.seller_id = auth.uid()
        )
    )
);

-- 8. Index database
create index idx_orders_buyer
on public.orders(buyer_id);

create index idx_orders_seller
on public.orders(seller_id);

create index idx_orders_event
on public.orders(event_id);

create index idx_orders_listing
on public.orders(listing_id);

create index idx_orders_status
on public.orders(status);

create index idx_orders_expires
on public.orders(expires_at);

create index idx_payments_escrow
on public.payments(escrow_status);

commit;
