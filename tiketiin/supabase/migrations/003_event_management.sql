-- TIKETIIN DATABASE
-- Tahap 03: Event Management

begin;

-- 1. Tabel venues
create table public.venues (
    id integer generated by default as identity primary key,
    name text not null,
    address text not null default '',
    city text not null,
    latitude double precision not null
        check (latitude between -90 and 90),
    longitude double precision not null
        check (longitude between -180 and 180),
    created_by uuid references public.profiles(id),
    created_at timestamptz not null default now(),
    unique (name, city)
);

-- 2. Tabel events
create table public.events (
    id integer generated by default as identity primary key,
    name text not null,
    category text not null check (
        category in (
            'MUSIK',
            'OLAHRAGA',
            'SEMINAR',
            'PAMERAN',
            'SENI',
            'FILM'
        )
    ),
    venue_id integer not null
        references public.venues(id),
    date date not null,
    time text not null,
    description text not null default '',
    poster_url text,
    poster_start bigint not null default 4281025972,
    poster_end bigint not null default 4285627368,
    flash_ends_at timestamptz,
    base_sold integer not null default 0
        check (base_sold >= 0),
    base_wishlist integer not null default 0
        check (base_wishlist >= 0),
    view_count integer not null default 0
        check (view_count >= 0),
    views_last_7_days integer not null default 0
        check (views_last_7_days >= 0),
    created_by uuid references public.profiles(id),
    created_at timestamptz not null default now(),
    unique (name, venue_id, date)
);

-- 3. Mengaktifkan keamanan RLS
alter table public.venues enable row level security;
alter table public.events enable row level security;

revoke all on public.venues, public.events
from anon, authenticated;

grant select on public.venues, public.events
to anon, authenticated;

grant insert (name, address, city, latitude,
              longitude, created_by)
on public.venues to authenticated;

grant update (name, address, city, latitude, longitude)
on public.venues to authenticated;

grant insert (name, category, venue_id, date, time,
              description, poster_url, poster_start,
              poster_end, flash_ends_at, created_by)
on public.events to authenticated;

grant update (name, category, venue_id, date, time,
              description, poster_url, poster_start,
              poster_end, flash_ends_at)
on public.events to authenticated;

grant delete on public.venues, public.events
to authenticated;

-- 4. Kebijakan akses venues
create policy "Read venues"
on public.venues for select
to anon, authenticated
using (true);

create policy "Insert own venue"
on public.venues for insert
to authenticated
with check (
    auth.uid() = created_by
    and exists (
        select 1 from public.profiles
        where id = auth.uid()
        and is_kyc_verified = true
    )
);

create policy "Update own venue"
on public.venues for update
to authenticated
using (auth.uid() = created_by)
with check (auth.uid() = created_by);

create policy "Delete own venue"
on public.venues for delete
to authenticated
using (auth.uid() = created_by);

-- 5. Kebijakan akses events
create policy "Read events"
on public.events for select
to anon, authenticated
using (true);

create policy "Insert own event"
on public.events for insert
to authenticated
with check (
    auth.uid() = created_by
    and date >= current_date
    and exists (
        select 1 from public.profiles
        where id = auth.uid()
        and is_kyc_verified = true
    )
);

create policy "Update own event"
on public.events for update
to authenticated
using (auth.uid() = created_by)
with check (
    auth.uid() = created_by
    and date >= current_date
);

create policy "Delete own event"
on public.events for delete
to authenticated
using (auth.uid() = created_by);

-- 6. Index untuk pencarian
create index idx_events_category
on public.events(category);

create index idx_events_date
on public.events(date);

create index idx_events_venue
on public.events(venue_id);

commit;
